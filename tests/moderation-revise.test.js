import {test,before,after} from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import {testDB,user,initData,deps,env} from './helpers.js';
import {createApp} from '../server/app.js';
import {one} from '../server/db.js';
import {moderate,notifyReview} from '../server/domain.js';
let db,app,token;
before(async()=>{db=await testDB();await user(db,260,{moderation:'pending'});app=createApp(deps(db));token=(await request(app).post('/api/auth').send({initData:initData(260)})).body.token;});
after(()=>db.close());
const auth=r=>r.set('Authorization','Bearer '+token);
test('editing pending review withdraws old notices, retains photos, and invalidates old decisions',async()=>{
 const prior=await one(db,'SELECT revision,moderation FROM profiles WHERE user_id=260');
 assert.equal(prior.moderation,'pending');
 await db.tx(q=>notifyReview(q,env,'260'));
 assert.equal((await one(db,"SELECT count(*)::int AS n FROM outbox WHERE bot='admin' AND payload->>'review_user_id'='260' AND delivered_at IS NULL")).n,3);
 assert.equal((await auth(request(app).post('/api/profile/revise')).send({})).status,200);
 const draft=await one(db,'SELECT revision,moderation FROM profiles WHERE user_id=260');
 assert.equal(draft.moderation,'draft');assert.equal(draft.revision,prior.revision+1);
 assert.equal((await one(db,'SELECT step,data FROM registration_drafts WHERE user_id=260')).step,7);
 assert.equal((await one(db,"SELECT count(*)::int AS n FROM outbox WHERE bot='admin' AND payload->>'review_user_id'='260' AND delivered_at IS NULL")).n,0);
 assert.equal((await one(db,'SELECT count(*)::int AS n FROM photos WHERE user_id=260')).n,3);
 await assert.rejects(db.tx(q=>moderate(q,'1','260','approved','',prior.revision)),e=>e.status===409||e.code===409||e.message.includes('STALE_REVIEW'));
 assert.equal((await auth(request(app).post('/api/profile/submit')).send({consent:true})).status,200);
 const resubmitted=await one(db,'SELECT revision,moderation FROM profiles WHERE user_id=260');
 assert.equal(resubmitted.moderation,'pending');assert.equal(resubmitted.revision,draft.revision);
 const fresh=await db.query("SELECT payload FROM outbox WHERE bot='admin' AND payload->>'review_user_id'='260' AND delivered_at IS NULL");
 assert.equal(fresh.rows.length,3);
 assert.equal(fresh.rows[0].payload.review_revision,draft.revision);
 await assert.rejects(db.tx(q=>moderate(q,'1','260','approved','',prior.revision)));
 assert.equal((await one(db,'SELECT moderation FROM profiles WHERE user_id=260')).moderation,'pending');
});
